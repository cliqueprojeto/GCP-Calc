export const EMOJIS: EmojiItem[] = RAW.map(([e, k]) => ({ e, k: k.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase() }));

/** sugestões rápidas quando o "/" ainda não tem texto */
export const QUICK_EMOJIS = ['💰', '💸', '🧾', '🏠', '🛒', '🚗', '💡', '💊', '🎓', '🐾', '✈️', '🎁', '✅', '⚠️', '⭐', '→'];

export function searchEmoji(q: string, limit = 24): EmojiItem[] {
  const f = q.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim();
  if (!f) return QUICK_EMOJIS.map((e) => EMOJIS.find((x) => x.e === e)!).filter(Boolean);
  const starts = EMOJIS.filter((x) => x.k.split(' ').some((w) => w.startsWith(f)));
  const inc = EMOJIS.filter((x) => !starts.includes(x) && x.k.includes(f));
  return [...starts, ...inc].slice(0, limit);
}
